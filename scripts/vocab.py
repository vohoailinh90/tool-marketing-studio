#!/usr/bin/env python3
"""The vocabulary store: the data block inside vocab/vocab_standalone.html.

The owner studies English and Japanese words in a standalone HTML page. Each
new word is explained in a Claude Code chat, then folded into that page by this
script. The page carries its own data as one JSON array between two marker
comments, so there is a single source of truth and nothing to keep in step.

Everything computable lives here, not in a model: parsing the 5-column table
the chat produces, the duplicate key, the schema, the size limits that keep
whole passages out of the repository, and the byte-stable rewrite of the block.
Whether a meaning is right, or a register well chosen, is the session's job
(.claude/skills/vocab-study/SKILL.md).

    python3 scripts/vocab.py check                       # the store is valid and in canonical form (CI runs this)
    python3 scripts/vocab.py find "elaborate on"         # is it stored already?
    python3 scripts/vocab.py add --from batch.md --source "Ch.3 Tactical Empathy" --dry-run
    python3 scripts/vocab.py add --from batch.md --source "Ch.3 Tactical Empathy"
    python3 scripts/vocab.py list --new                  # the latest batch
    python3 scripts/vocab.py stats
    python3 scripts/vocab.py remove "dodge"

`add` reads a Markdown table (Từ/Cụm | Nghĩa tiếng Việt | Văn phong | Ghi chú | Nguồn)
or a JSON array (the page's backup file). It is all-or-nothing: one invalid row
and nothing is written. A word already stored is skipped; one stored with a
different content is reported, never overwritten unless --update.

Exit status: 0 done, 1 invalid input or an invalid store, 2 bad arguments or an unreadable file.
"""

from __future__ import annotations

import argparse
import datetime
import json
import os
import re
import sys
import tempfile
import unicodedata
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STORE = ROOT / "vocab" / "vocab_standalone.html"

BEGIN = "// <vocab-data>"
END = "// </vocab-data>"
BEGIN_LINE = f"{BEGIN} generated by scripts/vocab.py - add words with it, do not edit by hand"
PREFIX = "const SEED = "

# The page's REGISTER_COLORS must name exactly these (`check` compares them).
REGISTERS = ("Văn nói", "Văn viết", "Trung tính", "Chuyên nghiệp", "Chuyên ngành")
LANGS = ("EN", "JA")
FIELDS = ("term", "meaning", "register", "note", "source", "lang", "added")
REQUIRED = ("term", "meaning", "register", "source", "lang")
# Fields a backup file written by the page may carry without being part of an entry.
IGNORED_INPUT_FIELDS = ("id", "repo", "local")
# The size limits are the guard that keeps a pasted passage out of a public repository:
# a word, its meaning and one short example fit; a paragraph of someone's book does not.
LIMITS = {"term": 80, "meaning": 200, "note": 300, "source": 80}

JAPANESE = re.compile("[\u3040-\u309f\u30a0-\u30ff\u3400-\u4dbf\u4e00-\u9fff\uff66-\uff9f]")
KANA_READING = re.compile(r"\s*\([\u3040-\u309f\u30a0-\u30ff\u30fb\s]+\)$")
TRAILING_PAREN = re.compile(r"\s*\([^()]*\)$")
HEADER_CELL = re.compile(r"^(từ\s*/?\s*cụm|term)$", re.IGNORECASE)
SEPARATOR_CELL = re.compile(r"^:?-{2,}:?$")
ISO_DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")


class StoreError(Exception):
    """The store file is missing, unreadable or not in the shape this script writes."""


# ── Text helpers (mirrored by termKey in the page; tests/test_vocab.py compares them) ──────────

def nfc(text: str) -> str:
    return unicodedata.normalize("NFC", text)


def term_key(term: str) -> str:
    """The identity of a word: NFKC, lower case, one space between words, a kana reading dropped.

    `逸脱 (いつだつ)` and `逸脱` are the same word; `trigger (v)` and `trigger` are not
    (the parenthesis is part of the sense there), `headword` finds those.
    """
    text = re.sub(r"\s+", " ", unicodedata.normalize("NFKC", term)).strip().lower()
    return KANA_READING.sub("", text).strip()


def headword(term: str) -> str:
    """The key without any trailing parenthesis: `critical (= important)` -> `critical`."""
    return TRAILING_PAREN.sub("", term_key(term)).strip()


def detect_lang(term: str) -> str:
    return "JA" if JAPANESE.search(term) else "EN"


def source_key(source: str) -> str:
    """Two sources spelled `Ch.2 Mirroring` and `ch 2 - mirroring` are one source typed twice."""
    return re.sub(r"[\W_]+", "", unicodedata.normalize("NFKC", source).casefold())


def normalize_register(value: str) -> str:
    """`🗣 Văn nói` and `văn nói` -> `Văn nói`; anything else comes back unchanged for the validator."""
    bare = re.sub(r"^[^\w]+", "", nfc(value).strip())
    for register in REGISTERS:
        if bare.casefold() == register.casefold():
            return register
    return bare


# ── Entries ────────────────────────────────────────────────────────────────────────────────

def entry_problems(entry: object, where: str) -> tuple[list[str], list[str]]:
    """(errors, warnings) for one stored entry."""
    errors: list[str] = []
    warnings: list[str] = []
    if not isinstance(entry, dict):
        return [f"{where}: must be an object"], warnings
    for name in entry:
        if name not in FIELDS:
            errors.append(f"{where}: unknown field {name!r}")
    for name in REQUIRED:
        value = entry.get(name)
        if not isinstance(value, str) or not value.strip():
            errors.append(f"{where}: {name} is missing or empty")
    for name in ("note", "added"):
        if name in entry and not isinstance(entry[name], str):
            errors.append(f"{where}: {name} must be text")
    for name, limit in LIMITS.items():
        value = entry.get(name)
        if isinstance(value, str) and len(value) > limit:
            errors.append(f"{where}: {name} is {len(value)} characters, limit {limit}"
                          " (a word, one short example; never a passage)")
    for name in ("term", "meaning", "note", "source"):
        value = entry.get(name)
        if isinstance(value, str) and (value != value.strip() or re.search(r"[\r\n\t|]", value)):
            errors.append(f"{where}: {name} has a line break, tab or '|' or surrounding spaces")
    if isinstance(entry.get("register"), str) and entry["register"] not in REGISTERS:
        errors.append(f"{where}: register {entry['register']!r} is not one of {', '.join(REGISTERS)}")
    if isinstance(entry.get("lang"), str) and entry["lang"] not in LANGS:
        errors.append(f"{where}: lang {entry['lang']!r} is not one of {', '.join(LANGS)}")
    added = entry.get("added")
    if isinstance(added, str):
        try:
            if not ISO_DATE.match(added):
                raise ValueError(added)
            datetime.date.fromisoformat(added)
        except ValueError:
            errors.append(f"{where}: added {added!r} is not a YYYY-MM-DD date")
    term, lang = entry.get("term"), entry.get("lang")
    if isinstance(term, str) and lang in LANGS and detect_lang(term) != lang:
        warnings.append(f"{where}: lang {lang} but the term reads as {detect_lang(term)}")
    if isinstance(entry.get("note"), str) and not entry["note"].strip():
        warnings.append(f"{where}: no note (a nuance or an example is what makes a word stick)")
    return errors, warnings


def store_problems(entries: list[dict]) -> tuple[list[str], list[str]]:
    """Per-entry problems plus the ones only the whole list can see: duplicates and near-duplicates."""
    errors: list[str] = []
    warnings: list[str] = []
    seen: dict[str, str] = {}
    heads: dict[str, list[str]] = {}
    sources: dict[str, set[str]] = {}
    for index, entry in enumerate(entries, 1):
        label = entry.get("term") if isinstance(entry, dict) and isinstance(entry.get("term"), str) else "?"
        where = f"#{index} {label}"
        found_errors, found_warnings = entry_problems(entry, where)
        errors += found_errors
        warnings += found_warnings
        if not isinstance(entry, dict) or not isinstance(entry.get("term"), str):
            continue
        key = term_key(entry["term"])
        if key in seen:
            errors.append(f"{where}: the same word as {seen[key]!r}")
        seen[key] = entry["term"]
        heads.setdefault(headword(entry["term"]), []).append(entry["term"])
        if isinstance(entry.get("source"), str):
            sources.setdefault(source_key(entry["source"]), set()).add(entry["source"])
    for terms in heads.values():
        if len({term_key(term) for term in terms}) > 1:
            warnings.append(f"same headword, different sense: {' | '.join(terms)}")
    for spellings in sources.values():
        if len(spellings) > 1:
            warnings.append("one source spelled several ways: " + " | ".join(sorted(spellings)))
    return errors, warnings


def object_without_duplicate_keys(pairs: list[tuple[str, object]]) -> dict:
    result: dict = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"key {key!r} appears twice in one entry")
        result[key] = value
    return result


# ── The store file ─────────────────────────────────────────────────────────────────────────

def render_block(entries: list[dict]) -> str:
    """The text between the markers: one entry per line, so a batch is a clean diff."""
    lines = [BEGIN_LINE, f"{PREFIX}["]
    for entry in entries:
        ordered = {name: entry[name] for name in FIELDS if name in entry}
        text = json.dumps(ordered, ensure_ascii=False, separators=(", ", ": "))
        # `<` and the two line separators cannot end the script or the string literal this way.
        text = text.replace("<", "\\u003c").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
        lines.append(f"  {text},")
    lines += ["];", END]
    return "\n".join(lines)


@dataclass
class Store:
    path: Path
    text: str  # with \n line ends; `newline` puts the original ones back on save
    newline: str
    entries: list[dict] = field(default_factory=list)

    @classmethod
    def load(cls, path: Path) -> "Store":
        try:
            raw = path.read_bytes().decode("utf-8")
        except (OSError, UnicodeDecodeError) as exc:
            raise StoreError(f"{path}: cannot be read ({exc.__class__.__name__})") from exc
        newline = "\r\n" if "\r\n" in raw else "\n"
        text = raw.replace("\r\n", "\n")
        store = cls(path, text, newline)
        store.entries = store._parse()
        return store

    def _span(self) -> tuple[int, int]:
        begins = [m.start() for m in re.finditer(r"(?m)^" + re.escape(BEGIN), self.text)]
        ends = [m.end() for m in re.finditer(r"(?m)^" + re.escape(END) + r"[ \t]*$", self.text)]
        if len(begins) != 1 or len(ends) != 1 or ends[0] < begins[0]:
            raise StoreError(f"{self.path}: expected exactly one {BEGIN} ... {END} block, "
                             f"found {len(begins)} begin and {len(ends)} end markers")
        return begins[0], ends[0]

    def _parse(self) -> list[dict]:
        start, end = self._span()
        body = self.text[start:end].split("\n", 1)[1].rsplit("\n", 1)[0].strip()
        if not (body.startswith(PREFIX) and body.endswith(";")):
            raise StoreError(f"{self.path}: the data block must be `{PREFIX}[ ... ];` as written by this script")
        # Every entry ends in a comma (valid JavaScript) so a new word is a one-line diff; JSON allows none after the last.
        payload = re.sub(r",\s*\]$", "]", body[len(PREFIX):-1].strip())
        try:
            data = json.loads(payload, object_pairs_hook=object_without_duplicate_keys)
        except (ValueError, RecursionError) as exc:
            raise StoreError(f"{self.path}: the data block is not valid JSON ({exc})") from exc
        if not isinstance(data, list):
            raise StoreError(f"{self.path}: the data block must be a JSON array")
        return data

    def is_canonical(self) -> bool:
        """Whether the block is exactly what `render_block` writes, so a hand edit cannot hide in it."""
        start, end = self._span()
        return self.text[start:end] == render_block(self.entries)

    def render(self) -> str:
        start, end = self._span()
        text = self.text[:start] + render_block(self.entries) + self.text[end:]
        return text.replace("\n", self.newline) if self.newline != "\n" else text

    def save(self) -> None:
        """Write beside the file and replace it, so an interrupted run never leaves half a page."""
        data = self.render().encode("utf-8")
        handle, temp = tempfile.mkstemp(dir=self.path.parent, prefix=".vocab-", suffix=".tmp")
        try:
            with os.fdopen(handle, "wb") as out:
                out.write(data)
            os.replace(temp, self.path)
        except BaseException:
            Path(temp).unlink(missing_ok=True)
            raise
        self.text = data.decode("utf-8").replace("\r\n", "\n")

    def page_registers(self) -> list[str]:
        """The register names the page colours; they must be the ones this script accepts."""
        block = re.search(r"const REGISTER_COLORS = \{(.*?)\n\};", self.text, re.DOTALL)
        return re.findall(r'^\s*"([^"]+)":\s*\{', block.group(1), re.MULTILINE) if block else []


# ── Input: the table or JSON a chat produces ───────────────────────────────────────────────

def clean_cell(cell: str) -> str:
    cell = re.sub(r"\s*<br\s*/?>\s*", " ", cell)
    # The page shows text as it is stored, so Markdown decoration (bold, code) is dropped, not kept.
    cell = cell.replace("**", "").replace("`", "").strip()
    return nfc(re.sub(r"\s+", " ", cell))


@dataclass
class Row:
    where: str
    values: dict


def parse_table(text: str) -> tuple[list[Row], list[str]]:
    rows: list[Row] = []
    errors: list[str] = []
    for number, line in enumerate(text.splitlines(), 1):
        line = line.strip()
        if not line.startswith("|"):
            continue
        body = line[1:-1] if line.endswith("|") and len(line) > 1 else line[1:]
        cells = [clean_cell(cell) for cell in body.split("|")]
        if all(SEPARATOR_CELL.match(cell) or not cell for cell in cells):
            continue
        if HEADER_CELL.match(cells[0]):
            continue
        where = f"line {number}"
        if len(cells) > 5:
            errors.append(f"{where}: {len(cells)} cells, expected at most 5 (a '|' inside a cell?)")
            continue
        if len(cells) < 3:
            errors.append(f"{where}: {len(cells)} cells, need at least term | meaning | register")
            continue
        names = ("term", "meaning", "register", "note", "source")
        rows.append(Row(where, dict(zip(names, cells))))
    return rows, errors


def parse_json(text: str) -> tuple[list[Row], list[str]]:
    try:
        data = json.loads(text)
    except (ValueError, RecursionError) as exc:
        return [], [f"not valid JSON ({exc})"]
    if not isinstance(data, list):
        return [], ["a JSON input must be an array of entries"]
    rows: list[Row] = []
    errors: list[str] = []
    for index, item in enumerate(data, 1):
        where = f"entry {index}"
        if not isinstance(item, dict):
            errors.append(f"{where}: must be an object")
            continue
        unknown = [name for name in item if name not in FIELDS and name not in IGNORED_INPUT_FIELDS]
        if unknown:
            errors.append(f"{where}: unknown field(s) {', '.join(map(repr, unknown))}")
            continue
        values = {name: item[name] for name in FIELDS if name in item}
        if any(not isinstance(value, str) for value in values.values()):
            errors.append(f"{where}: every field must be text")
            continue
        rows.append(Row(where, {name: clean_cell(value) for name, value in values.items()}))
    return rows, errors


def parse_input(text: str) -> tuple[list[Row], list[str]]:
    return parse_json(text) if text.lstrip().startswith("[") else parse_table(text)


def build_entry(row: Row, source: str, date: str) -> tuple[dict | None, list[str], list[str]]:
    """A complete entry from one input row (or why it cannot be one), and what is worth a second look."""
    values = row.values
    entry = {
        "term": values.get("term", ""),
        "meaning": values.get("meaning", ""),
        "register": normalize_register(values.get("register", "")),
        "note": values.get("note", ""),
        "source": values.get("source") or source,
        "lang": values.get("lang") or detect_lang(values.get("term", "")),
        "added": values.get("added") or date,
    }
    errors, warnings = entry_problems(entry, row.where)
    return (None, errors, warnings) if errors else (entry, [], warnings)


# ── Add ────────────────────────────────────────────────────────────────────────────────────

SAME_FIELDS = ("meaning", "register", "note", "source", "lang")


@dataclass
class Report:
    added: list[dict] = field(default_factory=list)
    unchanged: list[dict] = field(default_factory=list)
    differs: list[tuple[dict, dict]] = field(default_factory=list)  # (stored, incoming)
    updated: list[dict] = field(default_factory=list)
    near: list[tuple[dict, dict]] = field(default_factory=list)  # (incoming, stored)
    errors: list[str] = field(default_factory=list)


def plan_add(entries: list[dict], incoming: list[dict], update: bool) -> Report:
    """Decide each incoming entry against the stored ones; nothing is written here."""
    report = Report()
    stored = {term_key(e["term"]): e for e in entries}
    heads: dict[str, dict] = {}
    for entry in entries:
        heads.setdefault(headword(entry["term"]), entry)
    batch: set[str] = set()
    for entry in incoming:
        key = term_key(entry["term"])
        if key in batch:
            report.errors.append(f"{entry['term']!r} appears twice in this batch")
            continue
        batch.add(key)
        old = stored.get(key)
        if old is None:
            near = heads.get(headword(entry["term"]))
            if near is not None:
                report.near.append((entry, near))
            report.added.append(entry)
        elif all(old.get(name) == entry.get(name) for name in SAME_FIELDS):
            report.unchanged.append(old)
        elif update:
            report.updated.append({**entry, **({"added": old["added"]} if "added" in old else {})})
        else:
            report.differs.append((old, entry))
    return report


def apply_add(entries: list[dict], report: Report) -> list[dict]:
    replaced = {term_key(e["term"]): e for e in report.updated}
    result = [replaced.get(term_key(e["term"]), e) for e in entries]
    return result + report.added


def short(entry: dict) -> str:
    return f"{entry['term']} — {entry['meaning']} [{entry['register']}] ({entry['source']})"


def print_report(report: Report, dry_run: bool) -> None:
    for entry in report.added:
        print(f"+ {short(entry)}")
    for entry in report.updated:
        print(f"* updated {short(entry)}")
    for entry in report.unchanged:
        print(f"= already stored, skipped: {entry['term']}")
    for old, new in report.differs:
        print(f"! {old['term']} is stored with different content, skipped (use --update to replace)")
        print(f"    stored: {short(old)}  note: {old.get('note', '')}")
        print(f"    new:    {short(new)}  note: {new.get('note', '')}")
    for new, old in report.near:
        print(f"~ {new['term']} shares its headword with stored {old['term']!r}: a second sense, or the same word?")
    verdict = "dry run, nothing written" if dry_run else "written"
    print(f"add: {len(report.added)} new, {len(report.updated)} updated, {len(report.unchanged)} already stored, "
          f"{len(report.differs)} differ ({verdict})")


# ── Commands ───────────────────────────────────────────────────────────────────────────────

def read_source(argument: str) -> str:
    if argument == "-":
        return sys.stdin.read()
    try:
        return Path(argument).read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError) as exc:
        raise StoreError(f"{argument}: cannot be read ({exc.__class__.__name__})") from exc


def command_check(store: Store, args: argparse.Namespace) -> int:
    errors, warnings = store_problems(store.entries)
    if store.page_registers() != list(REGISTERS):
        errors.append(f"the page's REGISTER_COLORS {store.page_registers()} must be exactly {list(REGISTERS)}")
    if not errors and not store.is_canonical():
        errors.append("the data block is not in the form scripts/vocab.py writes: run `python3 scripts/vocab.py fmt`")
    for warning in warnings:
        print(f"WARN {warning}")
    for error in errors:
        print(f"ERROR {error}")
    print(f"vocab: {len(store.entries)} word(s), {len(errors)} error(s), {len(warnings)} warning(s)")
    return 1 if errors else 0


def command_fmt(store: Store, args: argparse.Namespace) -> int:
    """Rewrite the block in the canonical form (after an edit made by hand). Refuses an invalid store."""
    errors, _ = store_problems(store.entries)
    if errors:
        print("\n".join(f"ERROR {error}" for error in errors))
        return 1
    if store.is_canonical():
        print("fmt: already in the canonical form")
        return 0
    store.save()
    print("fmt: rewritten")
    return 0


def command_add(store: Store, args: argparse.Namespace) -> int:
    rows, errors = parse_input(read_source(args.source_file))
    date = args.date or datetime.date.today().isoformat()
    if args.date and not ISO_DATE.match(args.date):
        print(f"error: --date must be YYYY-MM-DD, got {args.date!r}", file=sys.stderr)
        return 2
    incoming: list[dict] = []
    warnings: list[str] = []
    for row in rows:
        entry, row_errors, row_warnings = build_entry(row, nfc(args.source or ""), date)
        errors += row_errors
        warnings += row_warnings
        if entry:
            incoming.append(entry)
    if not rows and not errors:
        errors.append("no table rows or entries found in the input")
    report = plan_add(store.entries, incoming, args.update)
    errors += report.errors
    if errors:
        for error in errors:
            print(f"ERROR {error}")
        print(f"add: {len(errors)} problem(s) in the input, nothing written")
        return 1
    for warning in warnings:
        print(f"WARN {warning}")
    print_report(report, args.dry_run)
    if not args.dry_run and (report.added or report.updated):
        store.entries = apply_add(store.entries, report)
        found, _ = store_problems(store.entries)
        if found:  # cannot happen when the entries above were valid; never write a store `check` would refuse
            print("\n".join(f"ERROR {error}" for error in found))
            return 1
        store.save()
    return 0


def matches(entry: dict, query: str, everywhere: bool) -> bool:
    needle = term_key(query)
    fields = [entry["term"]] + ([entry["meaning"], entry.get("note", "")] if everywhere else [])
    return any(needle in term_key(text) for text in fields)


def command_find(store: Store, args: argparse.Namespace) -> int:
    found = [e for e in store.entries if matches(e, args.query, args.all_fields)]
    for entry in found:
        print(f"{short(entry)}  note: {entry.get('note', '')}")
    if not found:
        print(f"find: {args.query!r} is not stored")
    return 0 if found else 1


def latest_batch(entries: list[dict]) -> str:
    return max((e["added"] for e in entries if e.get("added")), default="")


def table(entries: list[dict]) -> str:
    lines = ["| Từ/Cụm | Nghĩa tiếng Việt | Văn phong | Ghi chú | Nguồn |", "|---|---|---|---|---|"]
    lines += [f"| {e['term']} | {e['meaning']} | {e['register']} | {e.get('note', '')} | {e['source']} |" for e in entries]
    return "\n".join(lines)


def command_list(store: Store, args: argparse.Namespace) -> int:
    entries = store.entries
    if args.new:
        latest = latest_batch(entries)
        entries = [e for e in entries if e.get("added") == latest] if latest else []
    if args.lang:
        entries = [e for e in entries if e["lang"] == args.lang]
    if args.source:
        entries = [e for e in entries if source_key(e["source"]) == source_key(args.source)]
    if args.format == "json":
        print(json.dumps(entries, ensure_ascii=False, indent=2))
    elif args.format == "md":
        print(table(entries))
    else:
        for entry in entries:
            print(short(entry))
    return 0


def command_stats(store: Store, args: argparse.Namespace) -> int:
    entries = store.entries

    def count(name: str) -> dict[str, int]:
        result: dict[str, int] = {}
        for entry in entries:
            result[entry.get(name) or "(none)"] = result.get(entry.get(name) or "(none)", 0) + 1
        return dict(sorted(result.items(), key=lambda item: (-item[1], item[0])))

    print(f"words: {len(entries)}  latest batch: {latest_batch(entries) or '(none dated)'}")
    for name in ("lang", "register", "source", "added"):
        print(f"{name}: " + ", ".join(f"{value} {number}" for value, number in count(name).items()))
    return 0


def command_remove(store: Store, args: argparse.Namespace) -> int:
    keys = {term_key(term) for term in args.terms}
    kept = [e for e in store.entries if term_key(e["term"]) not in keys]
    gone = [e for e in store.entries if term_key(e["term"]) in keys]
    missing = keys - {term_key(e["term"]) for e in gone}
    for entry in gone:
        print(f"- {short(entry)}")
    for key in sorted(missing):
        print(f"ERROR {key!r} is not stored")
    if missing:
        print("remove: nothing written")
        return 1
    if not args.dry_run:
        store.entries = kept
        store.save()
    print(f"remove: {len(gone)} removed ({'dry run, nothing written' if args.dry_run else 'written'})")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--store", type=Path, default=STORE, help="the HTML page that holds the words")
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("check", help="validate the store").set_defaults(run=command_check)
    commands.add_parser("fmt", help="rewrite the data block in the form this script writes").set_defaults(run=command_fmt)
    add = commands.add_parser("add", help="add words from a table or JSON file ('-' reads stdin)")
    add.add_argument("--from", dest="source_file", required=True, metavar="FILE")
    add.add_argument("--source", help="source for rows that carry none, e.g. 'Ch.3 Tactical Empathy'")
    add.add_argument("--date", help="batch date YYYY-MM-DD (default today)")
    add.add_argument("--update", action="store_true", help="replace a stored word whose content differs")
    add.add_argument("--dry-run", action="store_true", help="report only; write nothing")
    add.set_defaults(run=command_add)
    find = commands.add_parser("find", help="look a word up (exit 1 when it is not stored)")
    find.add_argument("query")
    find.add_argument("-a", "--all-fields", action="store_true", help="also search meaning and note")
    find.set_defaults(run=command_find)
    listing = commands.add_parser("list", help="print stored words")
    listing.add_argument("--new", action="store_true", help="only the latest batch")
    listing.add_argument("--lang", choices=LANGS)
    listing.add_argument("--source")
    listing.add_argument("--format", choices=("plain", "md", "json"), default="plain")
    listing.set_defaults(run=command_list)
    commands.add_parser("stats", help="counts by language, register, source and batch").set_defaults(run=command_stats)
    remove = commands.add_parser("remove", help="remove words by their exact term")
    remove.add_argument("terms", nargs="+")
    remove.add_argument("--dry-run", action="store_true")
    remove.set_defaults(run=command_remove)
    return parser


def main(argv: list[str] | None = None) -> int:
    try:
        args = build_parser().parse_args(argv)
    except SystemExit as exc:
        return 0 if exc.code == 0 else 2
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="backslashreplace")
    try:
        return args.run(Store.load(args.store), args)
    except StoreError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
